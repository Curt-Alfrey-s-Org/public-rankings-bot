#!/bin/bash
# Port Configuration Script for Rankings Bot
# Configures unique ports to avoid conflicts with other bots

set -e

# Colors
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

echo -e "${BLUE}=========================================${NC}"
echo -e "${BLUE}  Bot Port Configuration${NC}"
echo -e "${BLUE}=========================================${NC}"
echo ""

# Get script directory
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR/.."

# Prompt for API port
echo -e "${YELLOW}Enter API port for this bot:${NC}"
echo "  Suggested: 8003 for Rankings Bot (API); 8000 for Market Pie5 Bot"
read -p "API Port (8000-8010): " API_PORT

# Validate API port
if ! [[ "$API_PORT" =~ ^[0-9]+$ ]] || [ "$API_PORT" -lt 8000 ] || [ "$API_PORT" -gt 8010 ]; then
    echo "❌ Invalid port. Must be between 8000-8010"
    exit 1
fi

# Prompt for Frontend port
echo ""
echo -e "${YELLOW}Enter Frontend port for this bot:${NC}"
echo "  Suggested: 5174 for Rankings Bot frontend dev (Vite), 5173 for Market Pie5 Bot"
read -p "Frontend Port (5173-5183): " FRONTEND_PORT

# Validate Frontend port
if ! [[ "$FRONTEND_PORT" =~ ^[0-9]+$ ]] || [ "$FRONTEND_PORT" -lt 5173 ] || [ "$FRONTEND_PORT" -gt 5183 ]; then
    echo "❌ Invalid port. Must be between 5173-5183"
    exit 1
fi

echo ""
echo -e "${BLUE}Configuring ports...${NC}"

# Update start_api.sh
if [ -f "start_api.sh" ]; then
    sed -i "s/API_PORT:-[0-9]*/API_PORT:-$API_PORT/g" start_api.sh
    echo "✅ Updated start_api.sh"
else
    echo "⚠️  start_api.sh not found"
fi

# Update scripts/start_api.sh if it exists
if [ -f "scripts/start_api.sh" ]; then
    sed -i "s/API_PORT:-[0-9]*/API_PORT:-$API_PORT/g" scripts/start_api.sh
    echo "✅ Updated scripts/start_api.sh"
fi

# Update frontend/vite.config.ts
if [ -f "frontend/vite.config.ts" ]; then
    sed -i "s/target: 'http:\/\/localhost:[0-9]*'/target: 'http:\/\/localhost:$API_PORT'/g" frontend/vite.config.ts
    sed -i "s/target: 'ws:\/\/localhost:[0-9]*'/target: 'ws:\/\/localhost:$API_PORT'/g" frontend/vite.config.ts
    sed -i "s/port: [0-9]*,/port: $FRONTEND_PORT,/g" frontend/vite.config.ts
    echo "✅ Updated frontend/vite.config.ts"
else
    echo "⚠️  frontend/vite.config.ts not found"
fi

# Create .env.ports file
cat > .env.ports << EOF
# Port Configuration
# Generated by scripts/configure_ports.sh
API_PORT=$API_PORT
FRONTEND_PORT=$FRONTEND_PORT
EOF
echo "✅ Created .env.ports"

echo ""
echo -e "${GREEN}=========================================${NC}"
echo -e "${GREEN}  Port Configuration Complete!${NC}"
echo -e "${GREEN}=========================================${NC}"
echo ""
echo "Configuration:"
echo "  API Port: $API_PORT"
echo "  Frontend Port: $FRONTEND_PORT"
echo ""
echo "Next steps:"
echo "  1. Restart API: ./start_api.sh"
echo "  2. Restart Frontend: cd frontend && npm run dev"
echo ""
